/**
 * HttpBrainAdapter — BrainPort implementation backed by the Brain REST API.
 *
 * Provides concrete implementations of `archivePostmortem` and `archiveLesson`
 * that delegate to `archiveKnowledge` with the reserved category + tag
 * conventions defined in the campaign orchestrator design (Phase 9).
 *
 *   - postmortem: category `vauban_postmortem`, tags `["postmortem", "campaign:<slug>", "outcome:<outcome>"]`
 *   - lesson:     category `vauban_lesson`,     tags `["lesson", ...applies_to]`
 *
 * Auth: OAuth 2.1 bearer token (BRAIN_TOKEN env var) or x-api-key
 * (BRAIN_API_KEY env var). At least one must be present.
 *
 * ─── V12 planes (working / episodic / claims) — sprint-895, ADR-ECO-114 ───
 *
 * Wire paths verified against the deployed Brain server (2026-07-06):
 * `brain-protocol/src/routes/index.ts` mounts, `working-memory.routes.ts`,
 * `episodic.routes.ts`, `schemas/working-memory.schema.ts`,
 * `schemas/episodic.schema.ts`, `types/index.ts`.
 *
 * - `working` (WorkingMemoryPort) — wired to `/api/memory/working/:agentId`
 *   (Redis-backed, wm.service.ts). REQUIRES `HttpBrainAdapterOptions.agentId`:
 *   the deployed WM REST surface keys every slot by an `:agentId` path
 *   segment that `WorkingMemoryPort.set/get/delete/list` do not themselves
 *   carry per-call (only `runId`/`key`). Feature-detected: omitted (left
 *   `undefined`) when `agentId` is not supplied, per the "no throw on a
 *   missing plane" contract.
 * - `episodic` (EpisodicMemoryPort) — wired to
 *   `/api/memory/episodic/:agentId/events` (Postgres-backed, em.service.ts).
 *   Every method carries its own `agentId` argument, so this plane is always
 *   wired. Two wire gaps, both handled honestly rather than silently:
 *     1. `metadata`/`artifacts`/`traceId` on `append()` have no field in
 *        `EpisodicAppendBodySchema` — dropped with a console.warn, never
 *        silently discarded.
 *     2. `queryByTrace()` cannot be implemented: the deployed schema/response
 *        type carries no `trace_id` column (verified against
 *        `types/index.ts` `EpisodicEvent` + `episodic.schema.ts`) — returns
 *        `[]` with a console.warn rather than fabricating a match.
 * - `claims` (ClaimPort) — wired to `POST /api/memory/claims` (assert) and
 *   `POST /api/memory/claims/query` (query), now that Brain ships a REST
 *   surface for it (brain-protocol commit `66af575b`,
 *   `src/routes/claims.routes.ts` + `src/schemas/claims.schema.ts`, verified
 *   2026-07-06). Always wired — like `episodic`, neither method needs the
 *   adapter-level `agentId` WM requires. Two wire gaps, both handled the same
 *   honest way as the WM/EM gaps above:
 *     1. `ClaimAssertOptions.agentId` IS sent — `ClaimAssertInputSchema` gained
 *        an optional `agentId` field (brain-protocol #101) that Brain persists
 *        to `knowledge_claims.model_id`, the same column `claim_query`'s
 *        `agentId` filter reads. REQUIRES a Brain deployed with #101 ; against
 *        an older `.strict()` schema, sending `agentId` would 400.
 *     2. `scope`/`ClaimAssertOptions.scope` has no wire field either
 *        (documented directly on `ports/brain.ts` `MemoryScope`: "an
 *        HTTP-backed ClaimPort should not send it to claim_assert until
 *        Brain ships that parameter") — not sent; the returned `Claim.scope`
 *        is the SDK-local governance value the caller asked for (default
 *        "private"), not an echo of a server-side field.
 *   Graceful degradation for older (pre-claims) Brain deployments: the plane
 *   is always present on `BrainPort` (never `undefined`) — a deployment that
 *   lacks the route surfaces as a typed `BrainUnavailableError` from
 *   `assert`/`query` (404/`no such route`), exactly like any other transport
 *   failure on this adapter; construction never throws.
 *
 * Governance (rules/knowledge/memory-planes.md, EU AI Act Art. 19):
 * - `episodic.append`/`record` always send `sourceAgentId: agentId` — every
 *   write through this agent-facing adapter is agent-generated, so Brain can
 *   apply the 180-day retention floor.
 * - `archiveKnowledge` sends `source_agent_id: entry.source_agent_id ?? agentId`
 *   (verified against the deployed `/api/knowledge` — `CreateKnowledgeSchema`
 *   accepts `source_agent_id`, `knowledge.service.ts` persists it, brain-protocol
 *   PR #102). Same "agent-generated by default" convention as episodic; every
 *   runtime agent constructed with an adapter-level `agentId` (Forge, Bastion,
 *   Vauban Finance, Command Center) becomes attributable in the Cortex
 *   AgentStrip with zero call-site changes. Per-call `entry.source_agent_id`
 *   overrides when a caller needs to attribute to a different agent.
 * - `scope`/`memory_class` governance tags have no wire field yet on
 *   working/episodic (verified: neither schema declares one) — not
 *   fabricated here; this mirrors `ClaimPort`'s own documented
 *   deployed-vs-normative gap (`ports/brain.ts` `MemoryScope` doc).
 * - No PII-scrubbing pipeline lives in this adapter; callers must mask PII
 *   before calling `working`/`episodic`/`claims` per `knowledge/brain-archival.md`.
 */

