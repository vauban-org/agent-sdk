/** @public */
export interface HttpBrainAdapterOptions {
  /** Brain REST API base URL (e.g. https://brain.api.vauban.tech). */
  baseUrl: string;
  /** Brain instance UUID. */
  brainId: string;
  /** OAuth 2.1 bearer token. Takes precedence over apiKey. */
  token?: string;
  /** x-api-key fallback (legacy). */
  apiKey?: string;
  /** Request timeout in milliseconds (default: 10 000). */
  timeoutMs?: number;
  /**
   * Identity of the agent this adapter instance acts as. Required to wire
   * the `working` (Working Memory) plane — see the module doc above for why
   * the WM REST surface needs it but `WorkingMemoryPort` doesn't carry it
   * per-call. Omit to skip wiring `working` (feature-detected absent).
   */
  agentId?: string;
  /**
   * Sink for this adapter's internal warnings (transport failures, degraded
   * responses, unsupported-field drops). Defaults to `console.warn` —
   * preserves the historical behavior for server-side hosts (Forge, Bastion,
   * Vauban Finance, the OODA factory) that expect these on stderr. A host
   * with an interactive terminal surface (the preste CLI) should inject a
   * quiet or debug-gated sink instead: an un-routed `console.warn` can land
   * mid-redraw of a live TUI region and corrupt it (see
   * `standalone-provider-router.ts`'s `PRESTE_DEBUG_TOOL_ARGS` precedent, and
   * `command-center:sprint-1067:t3-brain-http-noise`).
   */
  logger?: (message: string, ...args: unknown[]) => void;
  /**
   * Make `queryKnowledge` THROW `BrainUnavailableError` when the Brain did not
   * answer (transport failure, non-2xx, or `success:false`), instead of
   * returning `[]`. Default `false` ; every existing caller keeps the
   * historical fail-soft behaviour with no edit.
   *
   * Why it exists: fail-soft collapses "this Brain is down" and "this Brain
   * has nothing" into the same empty array. A single-Brain caller can live
   * with that; a fan-out cannot, because it would report a dead Brain as one
   * that answered with no results, and its "some Brain was unreachable" signal
   * would be a field that can never be populated. `createMultiBrainPortFromEnv`
   * sets this on every delegate for exactly that reason. An empty `data` array
   * from a Brain that DID answer is still a plain empty result, never a throw.
   */
  throwOnQueryFailure?: boolean;
}

